#!/usr/bin/env node
/**
 * Write one changelog page per plugin, from the release manifest.
 *
 * Why these are files rather than a component: the wiki's search index is
 * built from the MDX, so a changelog rendered at runtime by a React component
 * is a changelog nobody can find. "Which release fixed the retarget crash?" is
 * the question this section exists to answer, and it is only answerable if the
 * words are on a page.
 *
 * Why generated rather than written: the same rule the rest of the wiki
 * follows — no page types a version, a date or a release note. These pages
 * carry hundreds of version numbers, which makes them the last place anyone
 * should be typing one. Regenerated on every build; hand edits are lost.
 *
 * Grouping is by minor series, so a plugin with forty releases has a
 * navigable page rather than a wall: `## 0.4.x` collects every 0.4 release,
 * and the table of contents becomes the version index.
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(root, 'content', 'docs', 'releases')

const SCHEMA = 1
const manifest = JSON.parse(readFileSync(join(root, 'data', 'manifest.json'), 'utf8'))
if (manifest.schemaVersion !== SCHEMA) {
  console.error(
    `gen-changelogs: manifest schemaVersion ${manifest.schemaVersion}, expected ${SCHEMA}. ` +
      `Read the manifest before changing this.`,
  )
  process.exit(1)
}

const GENERATED = '{/* Generated by tools/gen-changelogs.mjs. Edits here are lost. */}'

/** MDX reads `{` as an expression and `<` as a tag. Release notes are prose. */
const mdxSafe = (s) => s.replace(/\{/g, '&#123;').replace(/</g, '&lt;')

/**
 * Push a body's own headings below the version heading it sits under.
 *
 * A changelog body is written for a GitHub release page, where `### Added` is
 * a top-level section. Here it is nested under `## 0.4.x` and `### 0.4.0`, so
 * left alone it would sit level with the version it belongs to and shuffle the
 * table of contents into nonsense.
 */
const demote = (s) => s.replace(/^(#{1,4}) /gm, (_, h) => '#'.repeat(Math.min(h.length + 1, 6)) + ' ')

const slug = (id) => id.toLowerCase()

const compare = (a, b) => {
  const pa = a.split('.').map(Number)
  const pb = b.split('.').map(Number)
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const d = (pa[i] ?? 0) - (pb[i] ?? 0)
    if (d !== 0) return d
  }
  return 0
}

const minorOf = (v) => {
  const [maj, min] = v.split('.')
  return `${maj}.${min}.x`
}

const date = (iso) =>
  new Date(iso).toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' })

const DISTRIBUTION = {
  open: 'Open source',
  fab: 'Free, closed source',
  paid: 'Paid',
}

const setsById = new Map(manifest.sets.map((s) => [s.id, s]))
const byId = new Map(manifest.plugins.map((p) => [p.id, p]))

const stable = (p) => p.versions.filter((v) => v.channel === 'stable')

const latestOf = (p) =>
  stable(p).sort((a, b) => compare(b.version, a.version))[0]

/** One plugin's page: its facts, then every release it has, newest first. */
function pluginPage(p) {
  const set = setsById.get(p.set)
  const releases = stable(p)
  const dates = new Map(releases.map((v) => [v.version, v.releasedAt]))
  const entries = [...p.changelog].sort((a, b) => compare(b.version, a.version))
  const newest = latestOf(p)

  const description = newest
    ? `Every released version of ${p.id}, newest first. Latest ${newest.version}.`
    : `${p.id} has not been released yet.`

  const lines = [
    '---',
    `title: ${p.id}`,
    `description: ${description}`,
    `plugins: [${p.id}]`,
    'icon: ScrollText',
    '---',
    '',
    GENERATED,
    '',
    `| | |`,
    `|---|---|`,
    `| **Set** | ${set ? set.name : p.set} |`,
    `| **Role** | ${p.role} |`,
    `| **Latest** | ${newest ? `\`${newest.version}\` — ${date(newest.releasedAt)}` : 'unreleased'} |`,
    `| **Releases** | ${releases.length} |`,
  ]

  if (p.dependencies?.length) {
    lines.push(`| **Depends on** | ${p.dependencies.map((d) => `\`${d}\``).join(', ')} |`)
  }
  if (p.source) {
    lines.push(`| **Source** | [${p.source.replace(/^https?:\/\//, '')}](${p.source}) |`)
  }
  lines.push('')

  if (entries.length === 0) {
    lines.push(
      releases.length === 0
        ? 'Nothing has been released yet. The plugin exists in the register; that is a real state, not a missing page.'
        : 'This plugin has releases but no changelog bodies in the manifest.',
      '',
    )
  }

  let currentMinor = null
  for (const e of entries) {
    const minor = minorOf(e.version)
    if (minor !== currentMinor) {
      currentMinor = minor
      lines.push(`## ${minor}`, '')
    }
    const when = dates.get(e.version) ?? e.date
    lines.push(`### ${e.version}`, '', `*${date(when)}*`, '')
    const body = demote(mdxSafe(e.body)).trim()
    if (body) lines.push(body, '')
  }

  return lines.join('\n')
}

/** The index: every plugin, grouped by set, with where it has got to. */
function indexPage() {
  const totalStable = manifest.plugins.reduce((n, p) => n + stable(p).length, 0)

  const lines = [
    '---',
    'title: Changelogs',
    'description: Every released version of every plugin, one page per plugin, searchable.',
    'icon: ScrollText',
    '---',
    '',
    GENERATED,
    '',
    'One page per plugin, with its whole history on it. Search finds release',
    'notes the same way it finds anything else here, so *"which version fixed',
    'that"* is a query rather than an archaeology exercise.',
    '',
    `**${totalStable} released versions across ${manifest.plugins.length} plugins.**`,
    '',
    '<Callout type="info">',
    '  These pages are generated from the release manifest, which CI writes from',
    '  the git tags, the plugin descriptors and the published releases. Nothing',
    '  here is transcribed, so nothing here can disagree with what shipped.',
    '',
    '  For what happened recently across everything at once, the',
    '  [release log](/releases) is the same data as one feed.',
    '</Callout>',
    '',
  ]

  for (const s of manifest.sets) {
    const members = s.members.map((m) => byId.get(m)).filter(Boolean)
    if (members.length === 0) continue
    lines.push(`## ${s.name}`, '')
    lines.push('| Plugin | Role | Distribution | Latest | Released |', '|---|---|---|---|---|')
    for (const p of members) {
      const v = latestOf(p)
      lines.push(
        `| [${p.id}](/docs/releases/${slug(p.id)}) | ${p.role} | ` +
          `${DISTRIBUTION[p.distribution] ?? p.distribution} | ` +
          `${v ? `\`${v.version}\`` : '—'} | ${v ? date(v.releasedAt) : 'unreleased'} |`,
      )
    }
    lines.push('')
  }

  return lines.join('\n')
}

/** Sidebar order: the index, then each set's plugins under a separator. */
function metaFile() {
  const pages = ['index']
  for (const s of manifest.sets) {
    const members = s.members.map((m) => byId.get(m)).filter(Boolean)
    if (members.length === 0) continue
    pages.push(`---${s.name}---`)
    for (const p of members) pages.push(slug(p.id))
  }
  return JSON.stringify(
    {
      title: 'Changelogs',
      description: 'Release notes, one page per plugin',
      icon: 'ScrollText',
      root: true,
      pages,
    },
    null,
    2,
  )
}

mkdirSync(outDir, { recursive: true })

// A plugin removed from the register must lose its page, or the sidebar keeps
// pointing at a plugin that no longer exists.
const keep = new Set(['index.mdx', 'meta.json', ...manifest.plugins.map((p) => `${slug(p.id)}.mdx`)])
for (const f of readdirSync(outDir)) {
  if (!keep.has(f)) rmSync(join(outDir, f))
}

writeFileSync(join(outDir, 'meta.json'), metaFile() + '\n')
writeFileSync(join(outDir, 'index.mdx'), indexPage())
for (const p of manifest.plugins) {
  writeFileSync(join(outDir, `${slug(p.id)}.mdx`), pluginPage(p))
}

console.log(
  `changelogs: ${manifest.plugins.length} plugin pages + index (${outDir.replace(root + '\\', '')})`,
)
